package ua.zentix.incoming.client.fx.plume;

/**
 * Конденсированные продукты выхлопа — то, что делает струю светящейся, а след видимым: газ (CO₂, H₂O, N₂) в видимом
 * свете почти не излучает и не рассеивает. Числа — у 550 нм.
 * <ul>
 * <li>Массовое ослабление σ_m, м²/кг: τ = σ_m·∫ρ dl (Бугер–Ламберт–Бер). Для сферы диаметра d и плотности ρ_p
 * σ_m = 3·Q/(2·ρ_p·d), Q — фактор ослабления Ми (~2 у частиц крупнее длины волны).</li>
 * <li>Альбедо однократного рассеяния ω: доля ослабленного света, которая рассеивается, а не поглощается; цвет дыма —
 * {@link #reflectance}.</li>
 * <li>Поглощение горячих частиц в струе (1 − ω у раскалённых): от него — степень черноты пламени ({@code FlameModel}).</li>
 * </ul>
 */
public enum Smoke {
    /**
     * Al₂O₃ твёрдого топлива с алюминием: ω ≈ 0,99 (белый); частицы ~1,5 мкм (⚠ оценка: у среза сопла РДТТ средний
     * размер 1–4 мкм), ρ 3 950, Q ≈ 2,2 → σ_m ≈ 550 м²/кг (диапазон 300–1 000). Раскалённая жидкая окись алюминия
     * поглощает больше холодной: ⚠ оценка 0,1.
     */
    ALUMINA(550, 0.99, 0.1),
    /**
     * Соли двухосновного (баллиститного) топлива — стабилизаторы и пламегасители (соли калия и свинца), доли микрона:
     * ⚠ оценка d ≈ 0,3 мкм, ρ ~2 700, Q ~1 → σ_m ≈ 2 000 м²/кг; ω ≈ 0,95 (серо-белый); горячие — ⚠ 0,1.
     */
    SALTS(2_000, 0.95, 0.1),
    /**
     * Сажа: массовое поглощение 7,5 м²/г (Bond, Bergstrom 2006, у 550 нм) при ω ≈ 0,25 — ослабление 10 000 м²/кг; горячая
     * поглощает так же.
     */
    SOOT(10_000, 0.25, 0.75),
    /**
     * Лёд инверсионного следа: молодые кристаллы ~2 мкм (⚠ оценка, 1–3 мкм), ρ 917, Q ≈ 2 → σ_m ≈ 1 600 м²/кг; ω ≈ 0,999.
     */
    ICE(1_600, 0.999, 0);

    /** Асимметрия рассеяния вперёд (Хеньи–Гринстейн): дым и облака 0,6–0,8, ⚠ оценка 0,7. */
    public static final double ASYMMETRY = 0.7;

    /** Массовое ослабление, м²/кг. */
    public final double extinction;
    /** Альбедо однократного рассеяния. */
    public final double albedo;
    /** Доля поглощения раскалённых частиц в струе. */
    public final double hotAbsorption;

    Smoke(double extinction, double albedo, double hotAbsorption) {
        this.extinction = extinction;
        this.albedo = albedo;
        this.hotAbsorption = hotAbsorption;
    }

    /**
     * Отражение толстого слоя с альбедо ω (два потока, рассеяние вперёд с асимметрией g): R = (1 − s)/(1 + s),
     * s = √((1 − ω)/(1 − ω·g)) — во сколько раз густой дым светлее белой стены под тем же светом (линейно).
     * Белый дым Al₂O₃ — ~0,69, соли — ~0,44, сажа — ~0,02, лёд — ~0,89.
     */
    public static double reflectance(double albedo) {
        double s = Math.sqrt((1 - albedo) / (1 - albedo * ASYMMETRY));
        return (1 - s) / (1 + s);
    }
}
